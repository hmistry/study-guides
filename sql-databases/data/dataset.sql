CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL UNIQUE,
  name        text NOT NULL,
  country     char(2),                             -- NULL = unknown
  created_at  timestamptz NOT NULL,
  referred_by bigint REFERENCES users (id)
);

CREATE TABLE products (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL,
  category text NOT NULL,
  price    numeric(10, 2) NOT NULL CHECK (price > 0)
);

CREATE TABLE orders (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES users (id),
  status     text NOT NULL CHECK (status IN ('cart', 'pending', 'paid', 'cancelled')),
  created_at timestamptz NOT NULL
);

CREATE TABLE order_items (
  order_id   bigint NOT NULL REFERENCES orders (id),
  product_id bigint NOT NULL REFERENCES products (id),
  qty        int NOT NULL CHECK (qty > 0),
  unit_price numeric(10, 2) NOT NULL,            -- price when ordered; may differ from products.price
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE events (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users (id),
  type    text NOT NULL,                         -- view, add_to_cart, checkout
  at      timestamptz NOT NULL
);

CREATE TABLE employees (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  dept       text NOT NULL,
  manager_id bigint REFERENCES employees (id),   -- NULL = the CEO
  salary     int NOT NULL,
  hired_on   date NOT NULL
);

