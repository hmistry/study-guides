-- Run it from any other database (it drops and recreates `practice`):
--   psql -d postgres -f dataset.sql
-- Then connect with:  psql -d practice
-- Safe to re-run: every run starts from a clean copy.

DROP DATABASE IF EXISTS practice WITH (FORCE);   -- FORCE (PG 13+) disconnects open sessions first
CREATE DATABASE practice;
\c practice
